"""Kai's escape suite: what an agent can still get past, and what stops it.

usage: run_escape.py <kai> [--markdown FILE]

Each case in cases.json is handed to `kai hook claude` as the agent's tool
calls, the way Claude Code would send them. The hooks' answer is one of:

  stopped        a step was denied or blocked
  warned         nothing was blocked, but Kai added a warning
  gets through   every step was allowed

and must match the case's recorded `hooks` value. A case that now gets
stopped is good news, but still a mismatch: update cases.json so the
published results stay true. Exits 1 on any mismatch.

--markdown writes the results table published as docs/ESCAPES.md.
"""
import json
import os
import subprocess
import sys
import tempfile

kai = os.path.abspath(sys.argv[1])
md_out = sys.argv[sys.argv.index("--markdown") + 1] if "--markdown" in sys.argv else None
here = os.path.dirname(os.path.abspath(__file__))
cases = json.load(open(os.path.join(here, "cases.json"), encoding="utf-8"))["cases"]

home = tempfile.mkdtemp()
proj = os.path.join(home, "proj")
os.makedirs(proj)
env = dict(os.environ, KAI_HOME=tempfile.mkdtemp(), HOME=home)
env.pop("KAI_POLICY", None)


def outcome(event):
    event = dict(event)
    event.setdefault("hook_event_name", "PreToolUse")
    event.setdefault("cwd", proj)
    text = json.dumps(event).replace("{HOME}", home)
    out = subprocess.run([kai, "hook", "claude"], input=text, capture_output=True,
                         text=True, env=env, timeout=30).stdout
    if '"deny"' in out or '"decision":"block"' in out or '"decision": "block"' in out:
        return "stopped"
    if "Kai warning" in out:
        return "warned"
    return "gets through"


def run(case):
    steps = case.get("steps") or [{"tool_name": "Bash", "tool_input": {"command": case["bash"]}}]
    result = "gets through"
    for step in steps:
        r = outcome(step)
        if r == "stopped":
            return r
        if r == "warned":
            result = r
    return result


mismatches = 0
rows = []
for c in cases:
    got = run(c)
    ok = got == c["hooks"]
    mismatches += not ok
    rows.append((c, got))
    print(f"  {'ok  ' if ok else 'FAIL'} {got:12} {c['id']}"
          + ("" if ok else f"  (recorded: {c['hooks']})"))

total = len(rows)
stopped = sum(got == "stopped" for _, got in rows)
print(f"\n{stopped}/{total} stopped by hooks today, {mismatches} mismatch(es)")

if md_out:
    icon = {"stopped": "✅ stopped", "warned": "⚠️ warned", "gets through": "❌ gets through"}
    lines = [
        "<!-- Generated by tests/escape/run_escape.py --markdown docs/ESCAPES.md. Do not edit by hand. -->",
        "",
        "# Escape suite results",
        "",
        "What an AI agent can still do to reach a secret, send data out or switch Kai off, "
        "and which layer is meant to stop it. Every row is a test case in "
        "[`tests/escape/cases.json`](../tests/escape/cases.json); `make escape` re-runs them and "
        "fails if a result changes.",
        "",
        f"**Today the hooks stop {stopped} of {total} attempts.** The rest are the reason for the "
        "storage wall and the network wall's Block mode, and some aren't covered by any planned layer yet.",
        "",
        "How to read it:",
        "",
        "- **Hooks (measured)** is what `kai hook claude` answers on every run, with the default policy. "
        "Cursor and Codex hooks share the same checks.",
        "- **Meant to be closed by** is a plan, not a result, unless it says *Hooks*. "
        "The network wall's Block mode and the storage wall aren't measured here: Block mode "
        "hasn't been verified yet, and the storage wall isn't built.",
        "",
    ]
    area = None
    for c, got in rows:
        if c["area"] != area:
            area = c["area"]
            lines += ["", f"## {area}", "", "| Attempt | Hooks (measured) | Meant to be closed by |", "|---|---|---|"]
        lines.append(f"| {c['attempt']} | {icon[got]} | {c['closed_by']} |")
    with open(md_out, "w", encoding="utf-8") as f:
        f.write("\n".join(lines) + "\n")

sys.exit(1 if mismatches else 0)
